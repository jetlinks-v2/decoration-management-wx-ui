/** 固定资料按ID和兼容旧名称匹配，不受PC文件回执或提交方式影响。 */
export function fixedMaterialDocument(item:MaterialDefinition):FixedMaterialDocument|undefined {
 const fixed=fixedMaterialItem(item)
 return item.kind==='material'&&fixed?documents[fixed.id]:undefined
}
